package com.syron.app.domain.model

/**
 * يبني توجيه النظام المرسل إلى النموذج: القواعد الأساسية الثابتة ثم أسلوب الشخصية.
 * هذا من شؤون المحادثة، لذلك لا يقع داخل تعريف الشخصية نفسه.
 * الشخصية تغيّر الأسلوب فقط، ولا تلمس النموذج أو المفتاح (هذه إعدادات مستقلة).
 */
object SystemPrompt {
    private val BASE = """
أنت SYRON، مساعد ذكاء اصطناعي شخصي داخل تطبيق أندرويد.
- أجب بلغة المستخدم؛ وإن كتب بالعربية فأجب بالعربية.
- الشخصية تغيّر أسلوبك فقط، ولا تغيّر دقة المعلومات أبداً.
- كن صريحاً بشأن حدودك: إذا لم تعرف فقل إنك لا تعرف، ولا تختلق معلومات أو مصادر أو روابط.
- لا تدّعِ قدرات غير موجودة. في هذه النسخة أنت تتحدث نصياً فقط: لا تملك ذاكرة بين المحادثات، ولا ترى الشاشة أو الكاميرا، ولا تتحكم بالهاتف، ولا تبحث في الإنترنت.
- اجعل الردود مختصرة ومباشرة ما لم يُطلب التفصيل.
- لا تستخدم رموز Markdown مثل النجمتين أو علامة # لأن الشاشة لا تعرضها بعد.
""".trim()

    fun build(personality: Personality): String =
        BASE + "\n\nأسلوبك الحالي:\n" + personality.instructions
}
