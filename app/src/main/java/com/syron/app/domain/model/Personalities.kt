    /** يعيد الشخصية صاحبة المعرّف، أو null إن لم توجد. */
    fun find(id: String?): Personality? = all.firstOrNull { it.id == id }

    /** يعيد الشخصية صاحبة المعرّف، وإن كان مجهولاً أو null (مثلاً قيمة قديمة محفوظة) فالافتراضية. */
    fun byId(id: String?): Personality = find(id) ?: all.first { it.id == DEFAULT_ID }
